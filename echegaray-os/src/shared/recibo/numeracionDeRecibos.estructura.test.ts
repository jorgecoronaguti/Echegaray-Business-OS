test('CABLEADO: lo que se imprime lleva el número; la vista previa no inventa uno', () => {
  const hoja = leer('src/features/administracion/components/liquidacion/cuadro/HojaDelRecibo.tsx')
  assert.match(hoja, /rotuloDelNumero\(codigo\)/)
  assert.match(leer('src/features/administracion/components/liquidacion/cuadro/HojasDeRecibosA4.tsx'), /rotuloDelNumero\(r\.codigo\)/)
  assert.match(leer('src/features/administracion/services/recibosLotePdf.ts'), /rotuloDelNumero\(r\.codigo\)/)
  assert.match(leer('src/features/efectivo/services/reciboPdf.ts'), /rotuloDelNumero\(firma\.codigo\)/)
  // La ruta del PDF lee el código de lo guardado.
  assert.match(leer('src/app/(main)/administracion/personas/recibos-lote/route.ts'), /select\('id, codigo,/)
  const previa = leer('src/features/administracion/components/liquidacion/cuadro/VistaPreviaDeRecibos.tsx')
  // `.map(aLaHoja)` le pasaría el ÍNDICE como código: el recibo 3 de la vista previa diría «Recibo N° 2».
  assert.doesNotMatch(previa, /\.map\(aLaHoja\)/)
  assert.match(previa, /aLaHoja\(g\.recibo, g\.codigo\)/)
  // El individual imprime con el número ya dibujado: redibuja sincrónico antes de copiar el HTML.
  const armar = leer('src/features/administracion/components/liquidacion/cuadro/ArmarRecibo.tsx')
  assert.ok(armar.indexOf('flushSync(() => setCodigo(r.codigo))') > 0)
  assert.ok(armar.indexOf('flushSync(() => setCodigo(r.codigo))') < armar.indexOf('const salio = imprimir()'))
  assert.match(armar, /codigo=\{codigo\}/)
  assert.match(leer('src/features/administracion/components/RecibosEmitidos.tsx'), /codigo=\{r\.codigo\}/)
})

